export class TranslationManager {
  constructor() {
    this.currentLanguage = 'vi';
  }

  translateUI(lang) {
    this.currentLanguage = lang;
    const languageSelect = document.getElementById('language-select');
    if (languageSelect) {
      languageSelect.value = lang;
    }

    // Translate elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (translations[lang] && translations[lang][key]) {
        el.textContent = translations[lang][key];
      }
    });

    // Translate camera source select dropdown options
    const camSelect = document.getElementById('camera-source-select');
    if (camSelect) {
      Array.from(camSelect.options).forEach(opt => {
        if (opt.value === 'webcam') opt.text = lang === 'vi' ? 'Webcam hệ thống' : 'System Webcam';
        else if (opt.value === 'dslr_canon') opt.text = lang === 'vi' ? 'Canon EOS (Direct EDSDK)' : 'Canon EOS (Direct EDSDK)';
        else if (opt.value === 'dslr_sony') opt.text = lang === 'vi' ? 'Sony Alpha (REST API)' : 'Sony Alpha (REST API)';
      });
    }

    // Translate input placeholders
    const licenseInput = document.getElementById('license-input');
    const serverInput = document.getElementById('server-input');
    const roomInput = document.getElementById('room-input');
    const overlayInput = document.getElementById('overlay-input');
    if (translations[lang]) {
      if (licenseInput) licenseInput.placeholder = translations[lang].licensePlaceholder;
      if (serverInput) serverInput.placeholder = translations[lang].serverPlaceholder;
      if (roomInput) roomInput.placeholder = translations[lang].roomPlaceholder;
      if (overlayInput) overlayInput.placeholder = translations[lang].overlayPlaceholder;
    }
  }

  getTranslation(key) {
    return translations[this.currentLanguage]?.[key] || key;
  }
}
